#!/usr/bin/env python3
"""Generate Codex/Antigravity config from .claude/ (single source of truth).

.claude/skills/*            -> .agents/skills/*            (Codex + Antigravity)
.claude/commands/**/*.md    -> .agents/skills/<name>/SKILL.md
.claude/rules/<g>/<r>.md    -> .agents/rules/<g>-<r>.md    (Antigravity, needs `trigger:`)
.claude/agents/*.md         -> .codex/agents/*.toml        (Codex subagents)

Run from anywhere: python3 -I scripts/sync-ai-config.py
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".claude"
AGENTS = ROOT / ".agents"
CODEX_AGENTS = ROOT / ".codex" / "agents"

# Large reference-style rules load on demand instead of always-on (Antigravity 20k-token budget).
MODEL_DECISION_RULES = {"code-folder-structure"}

HEADER = "<!-- GENERATED by scripts/sync-ai-config.py from .claude/. Edit the source, then re-run. -->\n"
FM_RE = re.compile(r"^---\n(.*?)\n---\n?", re.S)


def split_frontmatter(text):
    m = FM_RE.match(text)
    if not m:
        return {}, text
    fm = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "\t")):
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"').strip("'")
    return fm, text[m.end():]


def first_summary(body):
    for line in body.splitlines():
        s = line.strip()
        if s.startswith(">"):
            s = re.sub(r"^>\s*(\*\*[^*]+\*\*:?\s*)?", "", s).strip()
            if s:
                return s
    for line in body.splitlines():
        if line.startswith("#"):
            return line.lstrip("# ").strip()
    return ""


def yaml_str(s):
    return json.dumps(s, ensure_ascii=False)


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def reset(path):
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True)


def sync_skills():
    out = AGENTS / "skills"
    reset(out)
    names = set()
    for d in sorted(p for p in (SRC / "skills").iterdir() if (p / "SKILL.md").is_file()):
        shutil.copytree(d, out / d.name, ignore=shutil.ignore_patterns(".DS_Store"))
        names.add(d.name)
    for f in sorted((SRC / "commands").rglob("*.md")):
        rel = f.relative_to(SRC / "commands").with_suffix("")
        name = slug("-".join(rel.parts))
        if name in names:
            continue
        fm, body = split_frontmatter(f.read_text(encoding="utf-8"))
        desc = fm.get("description") or first_summary(body) or f"Command /{'/'.join(rel.parts)}"
        desc = f"{desc} (from Claude command /{':'.join(rel.parts)})"
        (out / name).mkdir()
        (out / name / "SKILL.md").write_text(
            f"---\nname: {name}\ndescription: {yaml_str(desc)}\n---\n{HEADER}\n{body.lstrip()}",
            encoding="utf-8",
        )
        names.add(name)
    return len(names)


def sync_rules():
    out = AGENTS / "rules"
    reset(out)
    n = 0
    for f in sorted((SRC / "rules").rglob("*.md")):
        rel = f.relative_to(SRC / "rules").with_suffix("")
        name = slug("-".join(rel.parts))
        fm, body = split_frontmatter(f.read_text(encoding="utf-8"))
        trigger = "model_decision" if name in MODEL_DECISION_RULES else "always_on"
        desc = fm.get("description") or first_summary(body) or name
        (out / f"{name}.md").write_text(
            f"---\ntrigger: {trigger}\ndescription: {yaml_str(desc)}\n---\n{HEADER}\n{body.lstrip()}",
            encoding="utf-8",
        )
        n += 1
    return n


def sync_codex_agents():
    src = SRC / "agents"
    files = sorted(src.glob("*.md")) if src.is_dir() else []
    if CODEX_AGENTS.exists():
        shutil.rmtree(CODEX_AGENTS)
    if not files:
        return 0
    CODEX_AGENTS.mkdir(parents=True)
    for f in files:
        fm, body = split_frontmatter(f.read_text(encoding="utf-8"))
        name = fm.get("name") or f.stem
        if "'''" in body:
            raise SystemExit(f"{f}: body contains ''' which breaks TOML literal string")
        (CODEX_AGENTS / f"{name}.toml").write_text(
            f"# GENERATED by scripts/sync-ai-config.py from .claude/agents/{f.name}\n"
            f"name = {json.dumps(name, ensure_ascii=False)}\n"
            f"description = {json.dumps(fm.get('description', ''), ensure_ascii=False)}\n"
            f"developer_instructions = '''\n{body.strip()}\n'''\n",
            encoding="utf-8",
        )
    return len(files)


if __name__ == "__main__":
    print(f"skills: {sync_skills()} -> .agents/skills")
    print(f"rules: {sync_rules()} -> .agents/rules")
    print(f"codex agents: {sync_codex_agents()} -> .codex/agents")
